//! Less common but supported notation constructs remain first-class recipes.
use super::*;
pub(super) fn recipes(ty: Notation) -> Vec<Recipe> {
    use Notation::*;
    match ty {
        Sequence => vec![
            r("Named message", "semantics", "{id}: {from} -> {to} : {label:q}"),
            r("Creation message", "semantics", "{id}(kind=create): {from} -> {participant}+ : {label:q}"),
            r("Deletion message", "semantics", "{from} -> {participant}! : {label:q}"),
            r("Found message", "semantics", "? -> {to} : {label:q}"),
            r("Lost message", "semantics", "{from} -> ? : {label:q}"),
            r("Filled reply", "semantics", "(arrow=filled): <-- : {label:q}"),
            r("Ignore fragment", "semantics", "ignore {messages:q} {\n    {from} ->> {to} : {label:q}\n}"),
            r("Consider fragment", "semantics", "consider {messages:q} {\n    {from} ->> {to} : {label:q}\n}"),
            r("Nested fragment shorthand", "semantics", "strict alt {condition:q} {\n    {from} ->> {to} : {label:q}\n}"),
            bundle("Named fragment", "{id}: opt {condition:q} {\n    {from} ->> {to} : {label:q}\n}", "{id} covers {from},{to}"),
            bundle("Note", "{id}: note {label:q}", "{id} over {participant} : gap={gap}"),
            bundle("Continuation", "{id}: continuation {label:q}", "{id} spans {from},{to} : gap={gap}"),
            r("Time observation", "semantics", "at[{occurrence}] : time-observation={label:q}"),
            r("Time constraint", "semantics", "at[{occurrence}] : time-constraint={label:q}"),
            r("State annotation", "semantics", "at[{occurrence}] : state={label:q}"),
            r("Invariant", "semantics", "at[{occurrence}] : invariant={label:q}"),
            r("Action annotation", "semantics", "at[{occurrence}] : action={label:q}"),
            r("Duration observation", "semantics", "between[{first},{second}] : duration-observation={label:q}"),
            r("Duration constraint", "semantics", "between[{first},{second}] : duration-constraint={label:q}"),
            r("General ordering", "semantics", "order[{first},{second}]"),
            r("Coregion", "semantics", "coregion {participant} {\n    {first}\n    {second}\n}"),
            r("Inline decomposition", "semantics", "decompose {participant} {label:q} {\n    {child}\n    {other}\n    {child} ->> {other} : {message:q}\n}"),
            r("Interaction reference with gates", "semantics", "ref {label:q} {\n    {from} -> gate[{id}] : {message:q}\n}"),
            r("Occurrence order", "layout", "{first} above {second}"),
            r("Frame coverage", "layout", "{frame} covers {from},{to}"),
            r("Note placement", "layout", "{note} over {participant} : gap={gap}"),
            r("Continuation placement", "layout", "{continuation} spans {from},{to} : gap={gap}"),
        ],
        Class | C4Code => vec![
            r("Template class", "semantics", "class {id}<{parameter}>"),
            r("Template binding", "semantics", "{from} ..> {to} <<bind({parameter}->{classifier})>>"),
            r("Association with end annotations", "semantics", "{from} {source_multiplicity:q}/{source_role} -- {target_multiplicity:q}/{target_role} {to}"),
            r("N-ary association", "semantics", "association {id}\n{from} -- {id}\n{to} -- {id}\n{third} -- {id}"),
            r("Association class", "semantics", "association class {id} {\n    {name}: {classifier}\n}\n{id} .. relation[{relation}]"),
            r("Enumeration literal", "semantics", "{name}"),
        ],
        Object => vec![r("Literal slot", "semantics", "{name} = {value:q}")],
        Component | Composite => vec![
            r("Assembly connector", "semantics", "{from} == {to}"),
            r("Delegation connector", "semantics", "{from} => {to}"),
            r("Part", "semantics", "part {id}(of={classifier})"),
        ],
        Deployment => vec![
            r("Deployment", "semantics", "{from} ..> {to} <<deploy>>"),
            r("Manifestation", "semantics", "{from} ..> {to} <<manifest>>"),
        ],
        State => vec![
            r("Initial transition", "semantics", "initial {id}\n{id} --> {to}"),
            r("Choice with guarded exits", "semantics", "choice {id}\n{from} --> {id}\n{id} --> {to} : [{condition}]\n{id} --> {other} : [else]"),
            r("Entry behavior", "semantics", "entry / {effect}"),
            r("Do behavior", "semantics", "do / {effect}"),
            r("Exit behavior", "semantics", "exit / {effect}"),
            r("Transition", "semantics", "{from} --> {to} : {trigger} [{condition}] / {effect}"),
            r("Composite state", "semantics", "state {id} {\n    initial {start}\n    state {child}\n    {start} --> {child}\n}"),
        ],
        Activity => vec![
            r("Input pin", "semantics", "input {id}"),
            r("Output pin", "semantics", "output {id}"),
            r("Control flow", "semantics", "control {from} --> {to}"),
            r("Object flow", "semantics", "object {from} --> {to}"),
            r("Guarded control flow", "semantics", "control {from} --> {to} : [{condition}]"),
        ],
        UseCase => vec![
            r("Include", "semantics", "{from} ..> {to} <<include>>"),
            r("Extend", "semantics", "{from} ..> {to} <<extend>>"),
        ],
        Package => vec![
            r("Public import", "semantics", "{from} ..> {to} <<import>>"),
            r("Private import", "semantics", "{from} ..> {to} <<access>>"),
            r("Package merge", "semantics", "{from} ..> {to} <<merge>>"),
        ],
        Communication => vec![
            r("Numbered message", "semantics", "message {number} {from} --> {to} : {name}()"),
            r("Lifeline", "semantics", "object {id}(of={classifier})"),
        ],
        InteractionOverview => vec![
            r("Insert interaction on flow", "semantics", "interaction-use {id}(ref={classifier})\n{from} --> {id}\n{id} --> {to}"),
            r("Insert alternative on flow", "semantics", "decision {id}\nmerge {id}_Merge\ninteraction-use {id}_First(ref={classifier})\ninteraction-use {id}_Second(ref={other_interaction})\n{from} --> {id}\n{id} --> {id}_First : [{condition}]\n{id} --> {id}_Second : [else]\n{id}_First --> {id}_Merge\n{id}_Second --> {id}_Merge\n{id}_Merge --> {to}"),
            r("Insert parallel branches on flow", "semantics", "fork {id}\njoin {id}_Join\ninteraction-use {id}_First(ref={classifier})\ninteraction-use {id}_Second(ref={other_interaction})\n{from} --> {id}\n{id} --> {id}_First\n{id} --> {id}_Second\n{id}_First --> {id}_Join\n{id}_Second --> {id}_Join\n{id}_Join --> {to}"),
            r("Guarded flow", "semantics", "{from} --> {to} : [{condition}]"),
        ],
        Profile => vec![
            r("Metaclass", "semantics", "metaclass {classifier}"),
            r("Stereotype with extension", "semantics", "stereotype {id}\n{id} --^> {classifier}"),
            r("Profile with stereotype", "semantics", "profile {id} {\n    stereotype {name}\n    {name} --^> {classifier}\n}"),
            r("Stereotype extension", "semantics", "{from} --^> {to}"),
            r("Metaclass reference", "semantics", "{from} ..> {to} <<reference>>"),
            r("Profile application", "semantics", "{from} ..> {to} <<apply>>"),
            r("Strict profile application", "semantics", "{from} ..> {to} <<strict>>"),
            r("Stereotype property", "semantics", "{name}: {classifier}"),
        ],
        Bpmn => vec![
            r("Wrap root process in pool", "semantics", "pool {id}({label:q}) {\n}"),
            r("Conditional split", "semantics", "{from} <X>@{id} {to}:{condition} ; {other}:{otherwise}"),
            r("Parallel split", "semantics", "{from} <+>@{id} {to} ; {other}"),
            r("Inclusive split", "semantics", "{from} <O>@{id} {to}:{condition} ; {other}:{otherwise}"),
            r("Event-based split", "semantics", "{from} <event>@{id} {to} ; {other}"),
            r("Boundary error", "semantics", "{from} -(error@{id}:{label:q})-> {to}"),
            r("Non-interrupting boundary timer", "semantics", "{from} -(timer+@{id}:{label:q})-> {to}"),
            r("Flow attachments", "layout", "flow[{from}->{to}] : from={source_side}; to={target_side}; label-orientation={orientation}"),
        ],
        C4Context | C4Container | C4Component => vec![
            r("Relationship with technology", "semantics", "@{id}(technology={technology:q}) {from} -> {to} : {label:q}"),
        ],
        _ => vec![],
    }
}
